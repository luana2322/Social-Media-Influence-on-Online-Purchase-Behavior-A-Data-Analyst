export type Language = keyof typeof translations
export type TranslationKey = string

export function getTranslation(lang: Language, key: string): string {
  const keys = key.split(".");
  let result: any = translations[lang];
  for (const k of keys) {
    result = result?.[k];
  }
  return result || key;
}
